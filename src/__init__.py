# src 包：项目的所有源码都放在这个目录下
#
# 采用"分层"结构，让不同类型的代码各归其位，好处是：
#   以后项目变大，你能一眼知道"改什么去哪个目录"，而不是全堆在一个文件里。
#
#   config.py   -> 配置（步骤 1）
#   main.py     -> 程序入口（步骤 1）
#   utils/      -> 通用工具函数，如日志（步骤 1）
#   llm/        -> LLM 调用封装（步骤 2）
#   models/     -> Pydantic 数据模型（步骤 3）
#   agent/      -> Agent 主循环逻辑（步骤 4）
#   tools/      -> 搜索/抓取等工具（步骤 5）
